export const INCOTERM_IDS = INCOTERMS.map((item) => item.id)

export function getIncoterm(id) {
  return INCOTERMS.find((item) => item.id === id)
}

export function groupedIncoterms() {
  return {
    ANY: INCOTERMS.filter((item) => item.group === 'ANY'),
    SEA: INCOTERMS.filter((item) => item.group === 'SEA'),
  }
}

export function isModeCompatible(incotermId, mode) {
  const term = getIncoterm(incotermId)
  if (!term || !mode) return true
  return term.modes.includes(mode)
}
